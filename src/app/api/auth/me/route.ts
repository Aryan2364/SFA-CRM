import { NextResponse } from 'next/server'
import { getCurrentUser, requireUser, type SessionUser } from '@/lib/auth'
import { prisma } from '@/lib/db'
import { getTenantId } from '@/lib/tenant'
import { ALL_PERMISSION_KEYS, MASTER_SECTION_KEYS } from '@/lib/masters-registry'
import type { DataScope } from '@/lib/permissions'

// Every field below is the answer checkPermission() in src/lib/permissions.ts
// gives for that action, line for line: view `can_view`, create
// `can_create ?? can_edit`, edit `can_edit`, delete `can_delete`; all true for
// an Administrator; all false for NoRole or a section with no row. A
// Deactivated user gets a 401 rather than a map (see GET). `edit` used to
// be `can_edit || can_create`, which is wider than the server's — a
// create-only role was shown edit controls the routes refused.
// `create` is carried separately from `edit` because the server authorises
// them separately.
//
// ⚠️ `role_permissions.can_create` is `Boolean NOT NULL DEFAULT false` in
// prisma/schema.prisma, which is generated by `db pull` from the live
// database. So the `?? can_edit` arm is unreachable against today's schema and
// this field is exactly `can_create`. The expression is kept identical to
// permissions.ts's rather than simplified, so the two cannot drift if that
// column is ever made nullable. See src/lib/permissions.ts.
//
// `scope` is getDataScope()'s answer for the section, computed from the same
// rows rather than one query per section: 'all' for an Administrator and for
// every master section; otherwise the row's `data_scope`, and 'own' for NoRole,
// a section with no row, or a row with no scope.
type SectionPerm = { view: boolean; create: boolean; edit: boolean; delete: boolean; scope: DataScope }
type Permissions = Record<string, SectionPerm>

// The permission map the client reads. It carries the two points sections as
// well as the 23 storable ones, which is why it uses ALL_PERMISSION_KEYS rather
// than ALL_SECTIONS — see the note on POINTS_SECTIONS in the registry. This
// response never writes, so an unstorable key here is harmless.
const MASTER_SECTIONS: ReadonlySet<string> = new Set<string>(MASTER_SECTION_KEYS)
const allTrue: Permissions = ALL_PERMISSION_KEYS.reduce(
  (acc, s) => ({ ...acc, [s]: { view: true, create: true, edit: true, delete: true, scope: 'all' } }),
  {} as Permissions
)
const allFalse: Permissions = ALL_PERMISSION_KEYS.reduce(
  (acc, s) => ({
    ...acc,
    [s]: { view: false, create: false, edit: false, delete: false, scope: MASTER_SECTIONS.has(s) ? 'all' : 'own' },
  }),
  {} as Permissions
)

export async function GET() {
  if (!await getCurrentUser()) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

  // A verified session naming no tenant (the SuperAdmin payload) has no tenant
  // here; getTenantId() refuses it rather than fall back to the default tenant.
  let tid: string
  try {
    tid = getTenantId()
  } catch {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }

  // The role the routes authorise against, not the cookie's. requireUser()
  // re-reads it from the database — so a demoted Administrator loses
  // all-true here on the next read, and a newly promoted user gains it
  // without signing in again. Once the cookie above has verified, it throws
  // when the session is no longer honoured — credentials_version has moved
  // on since login, or the tenant is suspended or inactive. Every such
  // refusal is this route's 401, whatever the reason, so the body names none.
  let user: SessionUser
  try {
    user = await requireUser()
  } catch {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }
  // ⚠️ A DELIBERATE DIFFERENCE from requireUser(). A deactivated user
  // (users.status 'Inactive') is NOT rejected there: it returns them with
  // this role, and every route then refuses them through checkPermission().
  // Here that is a 401, not a 200 with no permissions: the client's session
  // probe signs out only on a 401, and the protected layout has no
  // deactivated screen, so a 200 would leave the user in an app where every
  // request fails. On the 401 the client signs out and login refuses them
  // with "Account is inactive" — a clear screen, and no loop.
  if (user.role === 'Deactivated') {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }

  // Mirrors the server's Administrator-only rules — creating users, setting a
  // password or role, deactivating/reactivating, editing or deleting an
  // Administrator's record — which the users routes check as
  // `user.role === 'Administrator'` on this same requireUser() role. They are
  // not a permission section, so the permission map cannot carry them; the UI
  // reads this flag instead of comparing role names itself.
  const isAdministrator = user.role === 'Administrator'

  const tenant = await prisma.tenants.findUnique({ where: { id: tid }, select: { name: true } })
  const tenantName: string = tenant?.name ?? ''

  // Subordinate count. Deliberately NOT tenant-scoped, matching the previous
  // query — viewer_user_id is already specific to this user. On the
  // tenant-scope allowlist (PLAN.md §8.2) with that reason.
  const countSubordinates = (viewerUserId: string) =>
    prisma.user_visibility.count({ where: { viewer_user_id: viewerUserId } })

  if (isAdministrator) {
    if (!user.userId) return NextResponse.json({ ...user, tenantName, isAdministrator, hasSubordinates: false, permissions: allTrue })
    const count = await countSubordinates(user.userId)
    return NextResponse.json({ ...user, tenantName, isAdministrator, hasSubordinates: count > 0, permissions: allTrue })
  }

  if (user.role === 'NoRole') {
    return NextResponse.json({ ...user, tenantName, isAdministrator, hasSubordinates: false, permissions: allFalse })
  }

  // Role-based user — fetch permissions + subordinate count
  const [visCount, permRows] = await Promise.all([
    user.userId ? countSubordinates(user.userId) : Promise.resolve(0),
    prisma.role_permissions.findMany({
      where: { tenant_id: tid, profile: user.role },
      select: { section: true, can_view: true, can_create: true, can_edit: true, can_delete: true, data_scope: true },
    }),
  ])

  const permissions: Permissions = { ...allFalse }
  for (const row of permRows) {
    if (ALL_PERMISSION_KEYS.includes(row.section)) {
      permissions[row.section] = {
        view: row.can_view,
        // The same expressions checkPermission() uses.
        create: row.can_create ?? row.can_edit,
        edit: row.can_edit,
        delete: row.can_delete,
        // The same expression getDataScope() uses.
        scope: MASTER_SECTIONS.has(row.section) ? 'all' : ((row.data_scope as DataScope | null) ?? 'own'),
      }
    }
  }

  return NextResponse.json({
    ...user,
    tenantName,
    isAdministrator,
    hasSubordinates: visCount > 0,
    permissions,
  })
}
